import { chromium } from 'playwright-core';
const URL = 'http://localhost:4173/gagyeboo/';
const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined });
const mk = async (vp, scheme) => { const c = await browser.newContext({ viewport: vp, locale: 'ko-KR', timezoneId: 'Asia/Seoul', colorScheme: scheme }); const p = await c.newPage(); await p.goto(URL); await p.waitForSelector('.empty'); await p.getByText('가상 데이터로 둘러보기').first().click(); await p.waitForSelector('.ledger, .cards'); await p.waitForTimeout(3500); return p; };
let p = await mk({ width: 390, height: 844 }, 'dark');
await p.locator('.breakdown-toggle').click();
await p.screenshot({ path: 'e2e/out/mobile-dark-chips.png' });
await p.locator('.breakdown-toggle').click();
await p.locator('.card .badge-btn').first().click();
await p.screenshot({ path: 'e2e/out/mobile-popover.png' });
await p.keyboard.press('Escape');
await p.locator('.card').first().click();
await p.waitForTimeout(400);
await p.screenshot({ path: 'e2e/out/mobile-edit.png' });
p = await mk({ width: 1366, height: 900 }, 'dark');
await p.screenshot({ path: 'e2e/out/desktop-dark.png' });
await p.locator('.tab', { hasText: '설정' }).click();
await p.locator('.side-item', { hasText: '화면' }).click();
await p.screenshot({ path: 'e2e/out/desktop-display.png' });
await p.locator('.side-item', { hasText: '목록 관리' }).click();
await p.locator('.subtab', { hasText: '지불수단' }).click();
await p.locator('.list-row .lr-main').first().click();
await p.waitForTimeout(300);
await p.screenshot({ path: 'e2e/out/desktop-payeditor.png' });
await browser.close();
